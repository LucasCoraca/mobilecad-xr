"""Writes desktop/font8x16.h: printable ASCII (32..126) as 8x16 1-bit glyphs rendered from DejaVu Sans Mono, used by the
desktop test app to draw its info panel (the Android app draws the panel with Android's Canvas instead)."""
import os
from PIL import Image, ImageDraw, ImageFont
F = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf', 13)
rows = []
for c in range(32, 127):
    im = Image.new('L', (8, 16), 0); ImageDraw.Draw(im).text((0, 0), chr(c), font=F, fill=255)
    rows.append([sum(1 << (7 - x) for x in range(8) if im.getpixel((x, y)) > 110) for y in range(16)])
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'desktop', 'font8x16.h')
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w') as f:
    f.write('// generated by tools/gen_font.py (DejaVu Sans Mono, Bitstream Vera license): ASCII 32..126, 8x16, MSB = left\n#pragma once\n')
    f.write('static const unsigned char kFont8x16[95][16] = {\n')
    for r in rows: f.write('  {' + ','.join('0x%02x' % b for b in r) + '},\n')
    f.write('};\n')
print(out)
